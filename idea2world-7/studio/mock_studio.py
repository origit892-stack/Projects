"""Runs the generated Luau project without Roblox.

This is the integration test that matters: it executes the real modules (MapConfig, WorldLayout,
TerrainBuilder, ... MapBootstrap) against `studio/luau_stub.lua`, which simulates the Roblox
DataModel. A generated world that fails here would also fail in Studio.

It also powers `MockStudio`, so the whole pipeline -- plan -> generate -> build -> validate -> report
-- can be exercised end to end in CI with no Studio session and no API key.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

STUB_PATH = Path(__file__).resolve().parent / "luau_stub.lua"
MODULE_ORDER = ["MapConfig", "WorldLayout", "AssetLibrary", "TerrainBuilder", "BiomeBuilder",
                "PathBuilder", "VegetationBuilder", "AssetPlacement", "BuildingBuilder",
                "LightingController", "AtmosphereController", "VFXController",
                "SoundscapeController", "SpawnSetup", "InteractionSetup", "MapValidator",
                "MapBootstrap"]


def luau_binary() -> str | None:
    return shutil.which("luau")


def _module_loader_block(sources: dict[str, str]) -> str:
    lines = ["local LOADERS = {}"]
    for name in MODULE_ORDER:
        if name not in sources:
            continue
        lines.append(f'LOADERS["{name}"] = function(script)')
        lines.append(sources[name])
        lines.append("end")
    return "\n".join(lines)


def build_harness(project_dir, extra_code: str = "") -> str:
    directory = Path(project_dir)
    sources = {}
    for name in MODULE_ORDER:
        path = directory / f"{name}.lua"
        if path.exists():
            sources[name] = path.read_text(encoding="utf-8")
    if not sources:
        raise FileNotFoundError(f"no generated modules in {directory}")
    stub = STUB_PATH.read_text(encoding="utf-8")
    # The stub declares `--!nocheck` and returns its table; wrap it in a function so the directive
    # stays a comment and the table is captured.
    stub_body = stub.replace("--!nocheck", "")
    return f"""-- Generated by studio/mock_studio.py -- Roblox simulator harness.
local STUB = (function()
{stub_body}
end)()

local Instance = STUB.Instance
local Enum = STUB.Enum
local CFrame = STUB.CFrame
local Vector3 = STUB.Vector3
local Vector2 = STUB.Vector2
local Color3 = STUB.Color3
local UDim2 = STUB.UDim2
local UDim = STUB.UDim
local NumberRange = STUB.NumberRange
local NumberSequence = STUB.NumberSequence
local NumberSequenceKeypoint = STUB.NumberSequenceKeypoint
local ColorSequence = STUB.ColorSequence
local ColorSequenceKeypoint = STUB.ColorSequenceKeypoint
local RaycastParams = STUB.RaycastParams
local DateTime = STUB.DateTime
local Random = STUB.Random
local TweenInfo = STUB.TweenInfo
local workspace = STUB.workspace
local game = STUB.game
local task = STUB.task
local typeof = STUB.typeof

local require
{_module_loader_block(sources)}

local ROOT = Instance.new("Folder")
ROOT.Name = "Idea2World_Generated_Map"
ROOT.Parent = game:GetService("ServerScriptService")
local moduleCache = {{}}
local moduleInstances = {{}}
for name in pairs(LOADERS) do
	local module = Instance.new("ModuleScript")
	module.Name = name
	module.Parent = ROOT
	moduleInstances[name] = module
end

require = function(target)
	if moduleCache[target] ~= nil then
		return moduleCache[target]
	end
	local loader = LOADERS[target.Name]
	if not loader then
		error("module not found: " .. tostring(target.Name))
	end
	local result = loader(target)
	if result == nil then
		result = true
	end
	moduleCache[target] = result
	return result
end

local ok, report = pcall(function()
	local Bootstrap = require(moduleInstances.MapBootstrap)
	return Bootstrap.build({{ verbose = false }})
end)

print("I2W_RESULT:" .. STUB.encode({{
	ok = ok,
	error = (not ok) and tostring(report) or nil,
	report = ok and report or nil,
	instanceCounts = STUB.instanceCounts,
	terrainFillCalls = STUB.terrainFillCalls,
}}))

{extra_code}
"""


def run_build(project_dir, timeout: int = 240, keep_harness: str | None = None) -> dict:
    binary = luau_binary()
    if not binary:
        return {"ok": False, "error": "luau interpreter not installed", "available": False}
    harness = build_harness(project_dir)
    directory = Path(keep_harness).parent if keep_harness else Path(tempfile.mkdtemp(prefix="i2w-sim-"))
    directory.mkdir(parents=True, exist_ok=True)
    harness_path = Path(keep_harness) if keep_harness else directory / "harness.lua"
    harness_path.write_text(harness, encoding="utf-8")
    try:
        proc = subprocess.run([binary, str(harness_path)], capture_output=True, text=True,
                              timeout=timeout, cwd=str(directory))
        output = (proc.stdout or "") + (proc.stderr or "")
    except subprocess.TimeoutExpired:
        return {"ok": False, "error": f"simulated build timed out after {timeout}s", "available": True}
    result = None
    for line in output.splitlines():
        if line.startswith("I2W_RESULT:"):
            try:
                result = json.loads(line[len("I2W_RESULT:"):])
            except json.JSONDecodeError:
                result = None
    if result is None:
        return {"ok": False, "error": "simulated build produced no result", "output": output[-4000:],
                "available": True}
    result["output"] = output[-4000:]
    result["available"] = True
    return result


class MockStudio:
    """A drop-in StudioMCPClient stand-in used by tests and by `--studio mock` runs."""

    name = "mock-studio"

    def __init__(self, project_dir):
        self.project_dir = Path(project_dir)
        self.connected = True
        self.last_output = ""
        self.instances = 0

    def start(self) -> "MockStudio":
        self.connected = True
        return self

    def close(self) -> None:
        self.connected = False

    def __enter__(self):
        return self.start()

    def __exit__(self, *_exc):
        self.close()

    def list_tools(self) -> list[dict]:
        return [{"name": name, "description": "simulated"} for name in
                ("execute_luau", "get_console_output", "screen_capture", "start_stop_play",
                 "search_game_tree", "inspect_instance", "generate_mesh", "generate_material")]

    def _wrap(self, payload: dict) -> dict:
        text = json.dumps(payload)
        return {"text": text, "json": payload, "images": [], "isError": bool(payload.get("error")),
                "raw": {"content": [{"type": "text", "text": text}]}}

    def execute_luau(self, code: str, timeout: float | None = None) -> dict:
        return self.call_tool("execute_luau", {"code": code})

    def console_output(self) -> str:
        return self.last_output

    def call_tool(self, name: str, arguments: dict | None = None) -> dict:
        arguments = arguments or {}
        if name == "execute_luau":
            result = run_build(self.project_dir)
            self.last_output = result.get("output", "")
            self.instances = sum((result.get("instanceCounts") or {}).values())
            report = result.get("report") or {}
            return self._wrap({
                "mode": "simulated",
                "passed": bool(report.get("passed")),
                "ok": bool(result.get("ok")),
                "report": report,
                "instanceCounts": result.get("instanceCounts") or {},
                "instances": self.instances,
                "error": result.get("error"),
            })
        if name == "get_console_output":
            return self._wrap({"output": self.last_output[-8000:]})
        if name in ("screen_capture", "start_stop_play", "search_game_tree", "inspect_instance"):
            return self._wrap({"simulated": True, "tool": name,
                               "note": "MockStudio cannot render or play; use a real Studio session."})
        if name == "generate_mesh":
            return self._wrap({"simulated": True, "mesh": arguments.get("prompt", "")[:120],
                               "note": "Mesh generation requires a real Studio MCP session."})
        if name == "generate_material":
            return self._wrap({"simulated": True})
        return self._wrap({"error": f"unknown tool {name}"})
