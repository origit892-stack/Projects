"""UI execution simulator.

Runs the generated native-UI Luau (UIConfig, Framework, UIBootstrap, UIServer) against
``studio/luau_stub.lua`` and verifies the UI actually builds and that a purchase round-trips
through the server-validated remote. This is the "the generated UI executes end-to-end" check,
mirroring the world build test. The stub body is inlined flat (it now `return`s its table) so the
inlined UI modules can share the harness scope, exactly like the world build harness.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

STUB_PATH = Path(__file__).resolve().parent / "luau_stub.lua"

HARNESS_TEMPLATE = r"""-- Idea2World 7.0 UI execution harness (generated by studio/ui_sim.py)
local STUB = (function()
__STUB_BODY__
end)()

local Instance = STUB.Instance
local game = STUB.game
local task = STUB.task
local workspace = STUB.workspace
local Players = game:GetService("Players")
local RS = game:GetService("ReplicatedStorage")
local SPS = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
local UDim2 = STUB.UDim2
local UDim = STUB.UDim
local Vector2 = STUB.Vector2
local Vector3 = STUB.Vector3
local Color3 = STUB.Color3
local CFrame = STUB.CFrame
local TweenInfo = STUB.TweenInfo
local CornerRadius = STUB.CornerRadius
local Enum = STUB.Enum

-- A simulated local player with a PlayerGui.
local player = Instance.new("Instance")
player.Name = "TestPlayer"
local playerGui = Instance.new("Instance")
playerGui.Name = "PlayerGui"
playerGui.Parent = player
Players.LocalPlayer = player
STUB._currentPlayer = player

local require
__UI_MODULE_BLOCK__

local uiEvents = {}

local uiFolder = Instance.new("Folder")
uiFolder.Name = "GameUI"
uiFolder.Parent = RS
for name in pairs(LOADERS) do
	local module = Instance.new("ModuleScript")
	module.Name = name
	module.Parent = uiFolder
end

local moduleCache = {}
require = function(target)
	local loader = LOADERS[target.Name]
	if not loader then error("ui module not found: " .. tostring(target.Name)) end
	if moduleCache[target.Name] ~= nil then return moduleCache[target.Name] end
	local result = loader(target)
	if result == nil then result = true end
	moduleCache[target.Name] = result
	return result
end

local ok, err = pcall(function()
	-- 1. Server boots: creates the remote + its OnServerEvent handler.
	require(uiFolder:WaitForChild("UIServer"))
	-- 2. Client boots: builds the ScreenGui + screens + HUD + connects the client remote.
	require(uiFolder:WaitForChild("UIBootstrap"))

	task.wait(0.5)
	local remote = RS:FindFirstChild("GameUI_Remote")
	assert(remote, "GameUI remote was not created")
	-- Record every client emission so the report can show the server's replies.
	local originalFire = remote.FireClient
	remote.FireClient = function(self, target, action, payload)
		table.insert(uiEvents, { action = action, payload = payload })
		return originalFire(remote, target, action, payload)
	end

	-- 3. Drive purchases the same way the client's Buy button does (FireServer shape).
	remote:FireServer("buy", { itemId = "boost_double", price = 250 })  -- affordable -> succeeds
	remote:FireServer("buy", { itemId = "pass_vip", price = 3000 })     -- too expensive -> rejected
end)

local guiFound = false
local screenCount = 0
local gui = playerGui:FindFirstChild("GameUI")
if gui then
	guiFound = true
	for _, child in ipairs(gui:GetChildren()) do
		if child.ClassName == "Frame" then
			screenCount += 1
		end
	end
end

local buyResults = {}
for _, e in ipairs(uiEvents) do
	if e.action == "buy_result" then
		table.insert(buyResults, e.payload)
	end
end

print("I2W_UI_RESULT:" .. STUB.encode({
	ok = ok,
	error = (not ok) and tostring(err) or nil,
	guiFound = guiFound,
	screens = screenCount,
	remotePresent = RS:FindFirstChild("GameUI_Remote") ~= nil,
	buyResults = buyResults,
	uiEventCount = #uiEvents,
}))
"""


def build_harness(sources: dict[str, str]) -> str:
    stub_body = STUB_PATH.read_text(encoding="utf-8").replace("--!nocheck", "")
    # Sources may be keyed "UIConfig.lua" or "UIConfig" -- normalise to bare module names.
    by_name = {k[:-4] if k.endswith(".lua") else k: v for k, v in sources.items()}
    ui_module_block = ["local LOADERS = {}"]
    for name in ("UIConfig", "Framework", "UIServer", "UIBootstrap"):
        if name not in by_name:
            continue
        ui_module_block.append(f'LOADERS["{name}"] = function(script)')
        ui_module_block.append(by_name[name])
        ui_module_block.append("end")
    harness = HARNESS_TEMPLATE
    harness = harness.replace("__STUB_BODY__", stub_body)
    harness = harness.replace("__UI_MODULE_BLOCK__", "\n".join(ui_module_block))
    return harness


def run_ui_sim(sources: dict[str, str], timeout: int = 120) -> dict:
    binary = shutil.which("luau")
    if not binary:
        return {"ok": False, "error": "luau interpreter not installed", "available": False}
    harness = build_harness(sources)
    directory = Path(tempfile.mkdtemp(prefix="i2w-ui-sim-"))
    harness_path = directory / "ui_harness.lua"
    harness_path.write_text(harness, encoding="utf-8")
    try:
        proc = subprocess.run([binary, str(harness_path)], capture_output=True, text=True,
                              timeout=timeout, cwd=str(directory))
        output = (proc.stdout or "") + (proc.stderr or "")
    except subprocess.TimeoutExpired:
        return {"ok": False, "error": f"UI simulation timed out after {timeout}s", "available": True}
    result = None
    for line in output.splitlines():
        if line.startswith("I2W_UI_RESULT:"):
            try:
                result = json.loads(line[len("I2W_UI_RESULT:"):])
            except json.JSONDecodeError:
                result = None
    if result is None:
        return {"ok": False, "error": "UI simulation produced no result", "output": output[-4000:],
                "available": True}
    result["available"] = True
    result["output"] = output[-3000:]
    result["passed"] = bool(result.get("ok") and result.get("guiFound") and _purchases_valid(result))
    return result


def _purchases_valid(result: dict) -> bool:
    """Affordable item succeeds; the too-expensive item is rejected server-side (2 replies)."""
    results = result.get("buyResults") or []
    if len(results) != 2:
        return False
    return {bool(r.get("ok")) for r in results} == {True, False}
