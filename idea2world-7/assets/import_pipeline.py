"""Import pipeline: get real 3D assets into the world.

Two sources of truth, in priority order for a generated map:

1. `generate_mesh` via the Roblox Studio MCP bridge -- native meshes, no upload step, ideal for
   organic subjects (trees, rocks, creatures, statues).
2. Local FBX/GLTF files (authored in Blender or licensed) imported through Roblox's mesh importer.
   Roblox does not accept local mesh files at runtime; import happens in Studio/Creator Hub, which is
   why this module produces a *plan* plus a ready Blender normalisation script rather than pretending
   it can upload for you.

Both paths land in `ReplicatedStorage/Idea2World_Meshes/<assetId>`, where `AssetLibrary` prefers them
over primitive recipes automatically.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

SUPPORTED_EXTENSIONS = {".fbx", ".gltf", ".glb", ".obj"}
MAX_UPLOAD_MB = 20.0


def blender_available() -> bool:
    return shutil.which("blender") is not None


def scan_assets(directory) -> dict:
    path = Path(directory)
    if not path.exists():
        return {"directory": str(path), "exists": False, "files": [], "issues": []}
    files, issues = [], []
    for item in sorted(path.iterdir()):
        if not item.is_file():
            continue
        suffix = item.suffix.lower()
        if suffix not in SUPPORTED_EXTENSIONS:
            continue
        size_mb = item.stat().st_size / (1024 * 1024)
        entry = {"name": item.stem, "file": str(item), "extension": suffix,
                 "size_mb": round(size_mb, 2), "valid": size_mb <= MAX_UPLOAD_MB}
        if size_mb > MAX_UPLOAD_MB:
            issues.append({"severity": "major", "file": item.name,
                           "message": f"{size_mb:.1f} MB exceeds the {MAX_UPLOAD_MB:.0f} MB mesh comfort limit"})
        files.append(entry)
    return {"directory": str(path), "exists": True, "files": files, "issues": issues,
            "blender_available": blender_available()}


def mesh_request_plan(spec) -> dict:
    """The generate_mesh queue, ordered so hero assets are produced first."""
    queue = []
    for asset in spec.asset_manifest.get("assets", []):
        if not asset.get("mesh_prompt"):
            continue
        category = asset.get("category", "prop")
        priority = {"structure": 0, "creature": 1, "vegetation": 2, "rock": 3, "prop": 4}.get(category, 5)
        queue.append({
            "assetId": asset["id"],
            "kind": asset["kind"],
            "category": category,
            "priority": priority,
            "prompt": asset["mesh_prompt"],
            "target": f"ReplicatedStorage/Idea2World_Meshes/{asset['id']}",
            "fallback": "layered part recipe (used automatically if the mesh is absent)",
            "targetTriangles": 900 if category in ("vegetation", "rock", "prop") else 2400,
            "scaleStuds": asset.get("height", 8),
        })
    queue.sort(key=lambda item: (item["priority"], item["assetId"]))
    return {"requests": queue, "count": len(queue),
            "note": ("Meshes are an upgrade, not a dependency: the map builds and validates with "
                     "recipes alone, then improves when meshes are present.")}


def blender_export_script(files: list[dict], out_dir: str = "processed") -> str:
    """Blender (background) script that normalises models: apply transforms, triangulate, centre, export GLB."""
    list_literal = ", ".join(f'"{Path(f["file"]).as_posix()}"' for f in files)
    return f'''"""Generated by Idea2World 6.0 -- run: blender -b -P this_script.py"""
import bpy, os, sys, math

SOURCES = [{list_literal}]
OUT_DIR = os.path.abspath("{out_dir}")
os.makedirs(OUT_DIR, exist_ok=True)

def reset():
    bpy.ops.wm.read_factory_settings(use_empty=True)

def normalise(name, source):
    reset()
    ext = os.path.splitext(source)[1].lower()
    if ext == ".obj":
        bpy.ops.wm.obj_import(filepath=source)
    elif ext in (".gltf", ".glb"):
        bpy.ops.import_scene.gltf(filepath=source)
    else:
        bpy.ops.import_scene.fbx(filepath=source)
    meshes = [o for o in bpy.context.scene.objects if o.type == "MESH"]
    if not meshes:
        print("SKIP (no mesh):", source)
        return
    bpy.ops.object.select_all(action="DESELECT")
    for obj in meshes:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = meshes[0]
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    # Roblox units are studs; normalise the tallest dimension to the requested height later in Studio.
    tallest = max(max(o.dimensions) for o in meshes) or 1.0
    factor = 1.0 / tallest
    for obj in meshes:
        obj.scale = (factor, factor, factor)
        obj.location = (obj.location.x * factor, obj.location.y * factor, obj.location.z * factor)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    for obj in meshes:
        if obj.data:
            obj.data.calc_normals_split() if hasattr(obj.data, "calc_normals_split") else None
            for polygon in obj.data.polygons:
                polygon.use_smooth = True
    target = os.path.join(OUT_DIR, name + ".glb")
    bpy.ops.export_scene.gltf(filepath=target, export_format="GLB", export_apply=True,
                              export_yup=True, use_selection=False)
    print("EXPORTED", target)

for source in SOURCES:
    name = os.path.splitext(os.path.basename(source))[0]
    try:
        normalise(name, source)
    except Exception as exc:
        print("FAILED", source, exc)
'''


def studio_import_plan(files: list[dict]) -> dict:
    steps = []
    for entry in files:
        steps.append({
            "assetId": "import_" + entry["name"],
            "source": entry["file"],
            "studioAction": "import_mesh",
            "requiresStudio": True,
            "note": ("Roblox mesh upload runs in Studio/Creator Hub. After import, rename the MeshPart "
                     "to the assetId and parent it under ReplicatedStorage/Idea2World_Meshes."),
        })
    return {"steps": steps, "count": len(steps), "blender_available": blender_available(),
            "blenderScript": blender_export_script(files) if files else ""}


def write_import_plan(project_dir, spec, assets_dir: str | None = None) -> dict:
    plan = {"meshRequests": mesh_request_plan(spec)}
    if assets_dir:
        scan = scan_assets(assets_dir)
        plan["localAssets"] = scan
        plan["import"] = studio_import_plan(scan["files"]) if scan["files"] else {"steps": []}
        if plan["import"].get("blenderScript"):
            script_path = Path(project_dir) / "blender_normalise.py"
            script_path.parent.mkdir(parents=True, exist_ok=True)
            script_path.write_text(plan["import"]["blenderScript"], encoding="utf-8")
            plan["blenderScriptPath"] = str(script_path)
    out = Path(project_dir) / "reports" / "asset_import_plan.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(plan, indent=2), encoding="utf-8")
    return plan
