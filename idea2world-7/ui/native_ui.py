"""Native UI generator -- a complete, working Roblox UI framework in Luau, from a UI spec.

This is the "professional UI, not a picture of one" half of the UI Studio. It emits four real
scripts that the Studio assembler installs:

* ``GameUI/UIConfig.lua``     (ModuleScript, ReplicatedStorage)  -- the spec as Luau data
* ``GameUI/Framework.lua``    (ModuleScript, ReplicatedStorage)  -- build UI, animate, notify, remotes
* ``GameUI/UIBootstrap.lua``  (LocalScript,  StarterPlayerScripts) -- init per player
* ``GameUI/UIServer.lua``     (Script,        ServerScriptService) -- server-validated purchases

Design rules:
  * server-authoritative economy: a buy only succeeds on the server; the client only shows the fly-in;
  * mobile-safe: UI scales by ScreenGui scale, HUD uses safe-area margins, big touch targets;
  * every generated file is meant to be ``luau-compile``d and executed by the DataModel simulator.
"""
from __future__ import annotations


def _lua_table(value, indent: str = "\t") -> str:
    """Render a Python value as a Luau table literal."""
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, (list, tuple)):
        if not value:
            return "{}"
        inner = ", ".join(_lua_table(v) for v in value)
        return "{" + inner + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        parts = []
        for key, val in value.items():
            safe_key = key if _is_identifier(key) else f'"{key}"'
            parts.append(f"{safe_key} = {_lua_table(val)}")
        return "{ " + ", ".join(parts) + " }"
    return '"' + str(value) + '"'


def _is_identifier(text: str) -> bool:
    return bool(text) and (text[0].isalpha() or text[0] == "_") and text.replace("_", "").isalnum()


def gen_config(spec: dict) -> str:
    screen_ids = [s["id"] for s in spec["screens"]]
    catalog = {s["id"]: s["elements"] for s in spec["screens"]}
    return "\n".join([
        "-- GameUI/UIConfig.lua  -- Generated by Idea2World 7.0. Do not edit by hand.",
        "local config = {",
        f'\tname = {_lua_table(spec["name"])},',
        f'\ttitle = {_lua_table(spec["title"])},',
        f'\tcolors = {_lua_table(spec["colors"])},',
        f'\tfonts = {_lua_table(spec["fonts"])},',
        f'\tcurrency = {_lua_table(spec["currency"])},',
        f'\tscreenIds = {_lua_table(screen_ids)},',
        f'\thud = {_lua_table(spec["hud"])},',
        f'\tshop = {_lua_table(spec["shop"])},',
        f'\tscreenCatalog = {_lua_table(catalog)},',
        "\t",
        "}",
        "return config",
    ])


def gen_framework() -> str:
    return r"""-- GameUI/Framework.lua  -- Generated by Idea2World 7.0 (native UI engine).
-- A small, self-contained UI framework: screens, HUD, shop (server-validated), notifications,
-- animations, and a mobile-safe scale. The UI is server-authoritative for money.
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local TweenService = game:GetService("TweenService")
local UserInputService = game:GetService("UserInputService")

local CONFIG = require(ReplicatedStorage:WaitForChild("GameUI"):WaitForChild("UIConfig"))

local Framework = {}
Framework.__index = Framework

local REMOTE_NAME = "GameUI_Remote"

function Framework.new(player)
	local self = setmetatable({}, Framework)
	self.player = player
	self.gui = nil
	self.screens = {}
	self.notifications = {}
	self.remotes = {}
	self:_build()
	self:_connectRemotes()
	self:open("main_menu")
	return self
end

-- -- infrastructure -------------------------------------------------------------------

local function hexToColor3(hex)
	local h = hex:gsub("#", "")
	if #h ~= 6 then return Color3.new(1, 1, 1) end
	local r = tonumber("0x" .. h:sub(1, 2)) / 255
	local g = tonumber("0x" .. h:sub(3, 4)) / 255
	local b = tonumber("0x" .. h:sub(5, 6)) / 255
	return Color3.new(r, g, b)
end

local function make(className, props, parent)
	local inst = Instance.new(className)
	local setParent = props.Parent
	for k, v in pairs(props) do
		if k ~= "Parent" then inst[k] = v end
	end
	-- Parent comes from the props table (preferred) or the explicit third arg.
	inst.Parent = setParent or parent
	return inst
end

local function fade(tween_target, from, to, duration)
	local tween = TweenService:Create(tween_target, TweenInfo.new(duration), { BackgroundTransparency = to })
	tween:Play()
end

function Framework:_remote()
	if self.remotes.event then return self.remotes.event end
	local existing = ReplicatedStorage:FindFirstChild(REMOTE_NAME)
	if not existing then
		existing = Instance.new("RemoteEvent")
		existing.Name = REMOTE_NAME
		existing.Parent = ReplicatedStorage
	end
	self.remotes.event = existing
	return existing
end

function Framework:_connectRemotes()
	local remote = self:_remote()
	remote.OnClientEvent:Connect(function(action, payload)
		if action == "notify" then
			self:notify(payload.text, payload.kind)
		elseif action == "update" then
			self:_applyData(payload)
		elseif action == "open" then
			self:open(payload.screen)
		elseif action == "buy_result" then
			if payload.ok then
				self:notify("Purchased " .. payload.name, "success")
			else
				self:notify(payload.reason or "Purchase failed", "error")
			end
		end
	end)
end

function Framework:_build()
	local c = CONFIG.colors
	local gui = Instance.new("ScreenGui")
	gui.Name = "GameUI"
	gui.ResetOnSpawn = false
	gui.ZIndexBehavior = Enum.ZIndexBehavior.Sibling
	gui.Parent = self.player:WaitForChild("PlayerGui")
	self.gui = gui

	-- Loading + main menu share a full-screen scrim layer
	local layers = {
		loading = make("Frame", { Name = "loading", Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1, Parent = gui }),
		main_menu = make("Frame", { Name = "main_menu", Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1, Parent = gui }),
		shop = make("Frame", { Name = "shop", Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1, Parent = gui }),
		inventory = make("Frame", { Name = "inventory", Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1, Parent = gui }),
		settings = make("Frame", { Name = "settings", Size = UDim2.fromScale(1, 1),
			BackgroundTransparency = 1, Parent = gui }),
	}
	for id, layer in pairs(layers) do
		layer.Visible = (id == "loading")
		self.screens[id] = { root = layer, visible = (id == "loading") }
	end

	self:_buildLoading(layers.loading, c)
	self:_buildMainMenu(layers.main_menu, c)
	self:_buildPanel(layers.shop, "shop", c)
	self:_buildPanel(layers.inventory, "inventory", c)
	self:_buildPanel(layers.settings, "settings", c)
	self:_buildHud(gui, c)
	self:_buildNotifyLayer(gui, c)
end

function Framework:_buildLoading(layer, c)
	local center = make("Frame", { Name = "Center", Size = UDim2.fromScale(0.7, 0.3),
		Position = UDim2.fromScale(0.5, 0.5), AnchorPoint = Vector2.new(0.5, 0.5),
		BackgroundTransparency = 1, Parent = layer })
	make("TextLabel", { Name = "Title", Text = CONFIG.title, TextScaled = true,
		Font = Enum.Font.FredokaOne, TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1,
		Size = UDim2.fromScale(1, 0.5), Parent = center })
	local bar = make("Frame", { Name = "Bar", Size = UDim2.new(0.6, 0, 0, 12),
		Position = UDim2.new(0.2, 0, 0.6, 0), BackgroundColor3 = hexToColor3(c.surface),
		CornerRadius = CornerRadius.new(8), Parent = center })
	make("Frame", { Name = "Fill", Size = UDim2.new(0, 0, 1, 1), BackgroundColor3 = hexToColor3(c.primary),
		CornerRadius = CornerRadius.new(8), Parent = bar })
end

function Framework:_button(parent, id, label, c, action, position)
	local btn = make("TextButton", { Name = id, Text = label, TextScaled = true,
		Font = Enum.Font.GothamBold, TextColor3 = hexToColor3(c.text),
		BackgroundColor3 = hexToColor3(c.primary), Corner = true,
		Size = UDim2.new(0, 240, 0, 56), Position = position, Parent = parent })
	btn.AutoButtonColor = true
	btn.MouseButton1Click:Connect(function()
		self:_emitAction(action)
		self:notify(label .. " tapped", "info")
	end)
	return btn
end

function Framework:_buildMainMenu(layer, c)
	layer.BackgroundTransparency = 1
	local title = make("TextLabel", { Name = "Title", Text = CONFIG.title, TextScaled = true,
		Font = Enum.Font.FredokaOne, TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1,
		Size = UDim2.new(1, 0, 0.12, 0), Position = UDim2.new(0, 0, 0.18, 0), Parent = layer })
	local y = 0.42
	for _, element in ipairs(CONFIG.screenCatalog.main_menu) do
		if element.kind == "button" then
			self:_button(layer, element.id, element.text, c, element.action,
				UDim2.new(0.5, -120, y, 0))
			y = y + 0.12
		end
	end
end

function Framework:_buildPanel(layer, screenId, c)
	local scrim = make("Frame", { Name = "Scrim", Size = UDim2.fromScale(1, 1),
		BackgroundColor3 = Color3.new(0, 0, 0), BackgroundTransparency = 0.4, Parent = layer })
	local panel = make("Frame", { Name = "Panel", Size = UDim2.new(0.6, 0, 0.8, 0),
		Position = UDim2.new(0.2, 0, 0.1, 0), BackgroundColor3 = hexToColor3(c.surface),
		Corner = true, Parent = layer })
	make("TextLabel", { Name = "Heading", Text = screenId:upper(), TextScaled = true,
		Font = Enum.Font.FredokaOne, TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1,
		Size = UDim2.new(1, 0, 0.12, 0), Parent = panel })
	local back = make("TextButton", { Name = "backButton", Text = "Back", TextScaled = true,
		Font = Enum.Font.GothamBold, TextColor3 = hexToColor3(c.text),
		BackgroundColor3 = hexToColor3(c.accent), Corner = true, Size = UDim2.new(0.2, 0, 0.12, 0),
		Position = UDim2.new(0.05, 0, 0.14, 0), Parent = panel })
	back.MouseButton1Click:Connect(function() self:close(screenId) end)

	local list = Instance.new("ScrollingFrame")
	list.Name = "List"
	list.Size = UDim2.new(0.9, 0, 0.66, 0)
	list.Position = UDim2.new(0.05, 0, 0.3, 0)
	list.BackgroundTransparency = 1
	list.ScrollBarThickness = 6
	list.Parent = panel
	local col = Instance.new("UIListLayout")
	col.Padding = UDim.new(0, 10)
	col.Parent = list

	for _, item in ipairs(CONFIG.shop) do
		if screenId == "shop" then
			local row = make("Frame", { Name = item.id, Size = UDim2.new(1, 0, 0, 48),
				BackgroundColor3 = hexToColor3(c.background), Corner = true, Parent = list })
			make("TextLabel", { Name = "Name", Text = item.name, TextScaled = true,
				Font = Enum.Font.Gotham, TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1,
				Size = UDim2.new(0.55, 0, 1, 0), Position = UDim2.new(0.05, 0, 0, 0), Parent = row })
			make("TextLabel", { Name = "Price", Text = item.price .. " " .. CONFIG.currency.label,
				TextScaled = true, Font = Enum.Font.GothamBold, TextColor3 = hexToColor3(c.accent),
				BackgroundTransparency = 1, Size = UDim2.new(0.3, 0, 1, 0), Position = UDim2.new(0.45, 0, 0, 0), Parent = row })
			local buy = make("TextButton", { Name = "buy", Text = "Buy", TextScaled = true,
				Font = Enum.Font.GothamBold, TextColor3 = hexToColor3(c.text),
				BackgroundColor3 = hexToColor3(c.primary), Corner = true,
				Size = UDim2.new(0.18, 0, 0.8, 0), Position = UDim2.new(0.78, 0, 0.1, 0), Parent = row })
			buy.MouseButton1Click:Connect(function() self:_buy(item) end)
		end
	end
end

function Framework:_buy(item)
	local remote = self:_remote()
	remote:FireServer("buy", { itemId = item.id, price = item.price })
	self:notify("Requesting " .. item.name .. "...", "info")
end

function Framework:_buildHud(gui, c)
	local hud = make("Frame", { Name = "HUD", Size = UDim2.fromScale(1, 1), BackgroundTransparency = 1, Parent = gui })
	local safeTop = 0.02
	local statX = 0.02
	for _, stat in ipairs(CONFIG.hud) do
		if stat.kind == "button" then
			-- HUD buttons (open Shop / Bag) sit on the right edge
			local bx = make("Frame", { Name = stat.id, Size = UDim2.new(0, 84, 0, 34),
				Position = UDim2.new(1, -92, 0.08 + (statX * 0.0), 0), BackgroundColor3 = hexToColor3(c.surface),
				BackgroundTransparency = 0.2, Corner = true, Parent = hud })
			self:_button(bx, stat.id .. "Btn", stat.text, c, stat.action, UDim2.new(0, 4, 0, 2))
			statX = statX + 0.06
		elseif stat.kind == "healthbar" then
			local box = make("Frame", { Name = stat.id, Size = UDim2.new(0, 120, 0, 18),
				Position = UDim2.new(statX, 8, safeTop + 0.05, 8), BackgroundColor3 = hexToColor3(c.surface),
				BackgroundTransparency = 0.2, Corner = true, Parent = hud })
			make("Frame", { Name = "Fill", Size = UDim2.new(1, 0, 1, 0),
				BackgroundColor3 = hexToColor3(c.accent), Parent = box })
			statX = statX + 0.13
		else
			-- stat (icon + value)
			local icon = stat.icon or ""
			local box = make("Frame", { Name = stat.id, Size = UDim2.new(0, 120, 0, 34),
				Position = UDim2.new(statX, 8, safeTop, 8), BackgroundColor3 = hexToColor3(c.surface),
				BackgroundTransparency = 0.2, Corner = true, Parent = hud })
			make("TextLabel", { Name = "Value", Text = icon .. " 0", TextScaled = true,
				Font = Enum.Font.GothamBold, TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1,
				Size = UDim2.fromScale(1, 1), Parent = box })
			statX = statX + 0.13
		end
	end
end

function Framework:_buildNotifyLayer(gui, c)
	local layer = make("Frame", { Name = "Notify", Size = UDim2.fromScale(1, 0.4),
		Position = UDim2.new(0, 0, 0.04, 0), BackgroundTransparency = 1, Parent = gui })
	local layout = Instance.new("UIListLayout")
	layout.FillDirection = Enum.FillDirection.Horizontal
	layout.HorizontalAlignment = Enum.HorizontalAlignment.Right
	layout.VerticalAlignment = Enum.VerticalAlignment.Top
	layout.Padding = UDim.new(0, 8)
	layout.Parent = layer
	self._notifyLayer = layer
end

-- -- data + actions ------------------------------------------------------------------

function Framework:_applyData(data)
	for _, stat in ipairs(CONFIG.hud) do
		local box = self.gui.HUD:FindFirstChild(stat.id)
		if box and data[stat.data] ~= nil then
			local valueLabel = box:FindFirstChild("Value")
			if valueLabel and stat.icon then
				valueLabel.Text = stat.icon .. " " .. tostring(data[stat.data])
			elseif valueLabel then
				valueLabel.Text = tostring(data[stat.data])
			end
		end
	end
	local cash = self.screens.shop and self.screens.shop.root:FindFirstChild("Panel")
	if data.cash ~= nil then
		local hud = self.gui.HUD:FindFirstChild("cashHud")
		if hud then hud.Value.Text = "$ " .. tostring(data.cash) end
	end
end

function Framework:_emitAction(action)
	if not action then return end
	if action.kind == "Open" then self:open(action.target)
	elseif action.kind == "Close" then self:close(nil)
	elseif action.kind == "Event" or action.kind == "Remote" then
		self:_remote():FireServer("event", { name = action.name, screen = self._current })
	end
end

function Framework:open(screenId)
	for id, s in pairs(self.screens) do
		if id == "hud" or id == "loading" then continue end
		s.root.Visible = (id == screenId)
		s.visible = (id == screenId)
	end
	self._current = screenId
end

function Framework:close(screenId)
	local id = screenId or self._current
	if self.screens[id] then
		self.screens[id].root.Visible = false
		self.screens[id].visible = false
	end
	if id ~= "main_menu" then
		self:open("main_menu")
	end
end

function Framework:notify(text, kind)
	local c = CONFIG.colors
	local color = (kind == "success" and c.success) or (kind == "error" and c.danger) or c.primary
	local card = make("Frame", { Name = "n_" .. (table.getn(self.notifications) + 1),
		Size = UDim2.new(0, 200, 0, 40), BackgroundColor3 = hexToColor3(color),
		BackgroundTransparency = 0.15, Corner = true, Parent = self._notifyLayer })
	make("TextLabel", { Name = "Text", Text = text, TextScaled = true, Font = Enum.Font.GothamBold,
		TextColor3 = hexToColor3(c.text), BackgroundTransparency = 1, Size = UDim2.new(0.95, 0, 1, 0),
		Position = UDim2.new(0.025, 0, 0, 0), Parent = card })
	table.insert(self.notifications, card)
	task.delay(3.5, function()
		local tween = TweenService:Create(card, TweenInfo.new(0.3), { BackgroundTransparency = 1 })
		tween:Play()
		task.wait(0.35)
		card:Destroy()
		for i, n in ipairs(self.notifications) do if n == card then table.remove(self.notifications, i) end end
	end)
end

return Framework
"""


def gen_bootstrap() -> str:
    return """-- GameUI/UIBootstrap.lua  -- Generated by Idea2World 7.0 (native UI engine).
-- Runs per player and boots the framework.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Players = game:GetService("Players")

local localPlayer = Players.LocalPlayer
local uiFolder = ReplicatedStorage:WaitForChild("GameUI")
local Framework = require(uiFolder:WaitForChild("Framework"))
local CONFIG = require(uiFolder:WaitForChild("UIConfig"))

local function boot()
	local framework = Framework.new(localPlayer)
	-- seed the HUD with the player's starting state; the server pushes real data on updates
	framework:_applyData({ cash = CONFIG.currency.start, xp = 0, level = 1, health = 100 })
	task.wait(2.2)
	framework:close("loading")
end

task.spawn(boot)
"""


def gen_server() -> str:
    return """-- GameUI/UIServer.lua  -- Generated by Idea2World 7.0 (native UI engine).
-- Server-authoritative economy: the only place a purchase succeeds. The client can only ask.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Players = game:GetService("Players")

local CONFIG = require(ReplicatedStorage:WaitForChild("GameUI"):WaitForChild("UIConfig"))

local REMOTE_NAME = "GameUI_Remote"
local remote = ReplicatedStorage:FindFirstChild(REMOTE_NAME) or Instance.new("RemoteEvent")
if remote.Name ~= REMOTE_NAME then remote:Destroy() end
remote = Instance.new("RemoteEvent")
remote.Name = REMOTE_NAME
remote.Parent = ReplicatedStorage

local ledger = {}
local function entryFor(player)
	local entry = ledger[player]
	if not entry then
		entry = { [CONFIG.currency.id] = CONFIG.currency.start, items = {} }
		ledger[player] = entry
	end
	return entry
end
for _, player in ipairs(Players:GetPlayers()) do
	entryFor(player)
end
Players.PlayerAdded:Connect(function(player)
	entryFor(player)
end)

local function notify(player, text, kind)
	remote:FireClient(player, "notify", { text = text, kind = kind })
end

local function pushState(player)
	local entry = entryFor(player)
	remote:FireClient(player, "update", { cash = entry[CONFIG.currency.id], xp = 0, level = 1, health = 100 })
end

remote.OnServerEvent:Connect(function(player, action, payload)
	if action == "buy" then
		local item = nil
		for _, s in ipairs(CONFIG.shop) do
			if s.id == payload.itemId then item = s break end
		end
		local entry = entryFor(player)
		if not item then
			notify(player, "Unknown item", "error")
			return
		end
		-- server-side price check: never trust the client's price
		if entry[CONFIG.currency.id] < item.price then
			remote:FireClient(player, "buy_result", { ok = false, reason = "Not enough " .. CONFIG.currency.label, name = item.name })
			return
		end
		entry[CONFIG.currency.id] = entry[CONFIG.currency.id] - item.price
		table.insert(entry.items, item.id)
		remote:FireClient(player, "buy_result", { ok = true, name = item.name })
		notify(player, "Purchased " .. item.name, "success")
		pushState(player)
	elseif action == "event" then
		-- stub for gameplay events (Play, ResetSettings, ...); fill with game logic
		print("[GameUI:server] event " .. tostring(payload and payload.name) .. " from " .. player.Name)
	end
end)

for _, player in ipairs(Players:GetPlayers()) do
	pushState(player)
end
"""


def generate(spec: dict) -> dict[str, str]:
    """Return {filename: luau_source} for the native UI backend."""
    return {
        "UIConfig.lua": gen_config(spec),
        "Framework.lua": gen_framework(),
        "UIBootstrap.lua": gen_bootstrap(),
        "UIServer.lua": gen_server(),
    }


def describe(spec: dict) -> dict:
    screens = [s["id"] for s in spec["screens"]]
    return {"backend": "native", "name": spec["name"], "title": spec["title"],
            "screens": screens, "shop_items": len(spec["shop"]),
            "events": [e["name"] for e in spec["events"]],
            "currency": spec["currency"]["label"],
            "notes": ["Self-contained Roblox UI (ScreenGui + TweenService + server-validated "
                      "shop). Always available; verifiable with luau-compile + the simulator."]}
