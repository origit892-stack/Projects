#!/usr/bin/env python3
"""Emit src/shared/config/Config.luau from all sibling JSON configs.

Roblox has no native JSON reader; Config.luau is the importable form (Studio +
headless luau tests). GENERATED FILE — never hand-edit; re-run after config changes.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
CONFIG_DIR = os.path.join(ROOT, "..", "src", "shared", "config")


def ident(key: str) -> str:
    if key and key[0].isalpha() and all(c.isalnum() or c == "_" for c in key) and key not in ("and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"):
        return key
    return json.dumps(key)


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def to_luau(v, indent: int = 0) -> str:
    pad = "  " * indent
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v == int(v) and abs(v) < 1e15:
            return str(int(v))
        return repr(v)
    if isinstance(v, str):
        return '"' + esc(v) + '"'
    if isinstance(v, list):
        if not v:
            return "{}"
        inner = ", ".join(to_luau(x, indent) for x in v)
        return "{ " + inner + " }"
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for k, x in v.items():
            val = to_luau(x, indent + 1)
            lines.append(f"{pad}  {ident(k)} = {val},")
        return "{\n" + "\n".join(lines) + f"\n{pad}}}"
    raise TypeError(f"unsupported type {type(v)}")


def main():
    names = sorted(n for n in os.listdir(CONFIG_DIR) if n.endswith(".json"))
    parts = []
    for name in names:
        with open(os.path.join(CONFIG_DIR, name)) as f:
            data = json.load(f)
        parts.append((name[:-5], data))
    header = [
        "-- GENERATED by scripts/emit_config_luau.py — DO NOT EDIT.",
        "-- Source of truth: the .json files next to this file (GDD v3, see docs/GDD_v3.md).",
        "-- Regenerate: python3 scripts/emit_config_luau.py",
        "local Config = {",
        "  _configVersion = 1,",
    ]
    for key, data in parts:
        header.append(f"  {key} = {to_luau(data, 1)},")
    header += ["}", "", "return Config"]
    out = os.path.normpath(os.path.join(CONFIG_DIR, "Config.luau"))
    with open(out, "w") as f:
        f.write("\n".join(header) + "\n")
    print(f"wrote {out} ({os.path.getsize(out)} bytes, {len(parts)} configs)")


if __name__ == "__main__":
    main()
