-- Lumio 3.3 additive migration. Existing profiles/tasks/connections and their data are unchanged.
-- This script can be safely re-run for table creation/policies.
create table if not exists public.school_items (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 kind text not null check(kind in ('exam','grade','announcement','timetable')),
 source text not null check(source in ('classroom','mashov','ofek','petel','shahaf','manual')),
 external_id text not null,
 title text not null,
 subject text not null default '',
 description text not null default '',
 event_date date,
 score numeric(5,2) check(score between 0 and 100),
 source_url text,
 day_of_week integer check(day_of_week between 0 and 6),
 start_time time,
 end_time time,
 room text,
 change_type text not null default 'normal' check(change_type in ('normal','cancelled','changed')),
 updated_at timestamptz not null default now(),
 unique(user_id,kind,source,external_id)
);
create index if not exists school_items_user_kind_idx on public.school_items(user_id,kind,event_date);
alter table public.school_items enable row level security;
revoke all on public.school_items from anon;
grant select,insert,update,delete on public.school_items to authenticated;
grant usage,select on sequence public.school_items_id_seq to authenticated;
drop policy if exists school_items_owner on public.school_items;
create policy school_items_owner on public.school_items for all to authenticated
 using ((select auth.uid())=user_id)
 with check ((select auth.uid())=user_id);
