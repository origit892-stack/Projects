create table if not exists public.profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default '', school text not null default 'קציר ב׳', city text not null default 'רחובות', grade text not null default 'ט׳', classroom text not null default '5', updated_at timestamptz not null default now()
);
create table if not exists public.tasks (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 source text not null check(source in ('classroom','mashov','ofek','petel','shahaf','manual')),
 external_id text not null,
 title text not null,
 subject text not null default '',
 description text not null default '',
 due_at timestamptz,
 source_url text,
 status text not null default 'todo' check(status in ('todo','progress','done')),
 updated_at timestamptz not null default now(),
 unique(user_id,source,external_id)
);
create index if not exists tasks_user_due_idx on public.tasks(user_id,due_at);
create table if not exists public.connections (
 user_id uuid not null references auth.users(id) on delete cascade,
 provider text not null check(provider in ('classroom','mashov','ofek','petel','shahaf')),
 state text not null check(state in ('not_connected','imported','api_connected')) default 'not_connected',
 last_sync_at timestamptz,
 last_error text,
 primary key(user_id,provider)
);
alter table public.profiles enable row level security;
alter table public.tasks enable row level security;
alter table public.connections enable row level security;
revoke all on public.profiles,public.tasks,public.connections from anon;
grant select,insert,update,delete on public.profiles,public.tasks,public.connections to authenticated;
grant usage,select on sequence public.tasks_id_seq to authenticated;
drop policy if exists profiles_owner on public.profiles;
create policy profiles_owner on public.profiles for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
drop policy if exists tasks_owner on public.tasks;
create policy tasks_owner on public.tasks for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
drop policy if exists connections_owner on public.connections;
create policy connections_owner on public.connections for all to authenticated using((select auth.uid())=user_id) with check((select auth.uid())=user_id);
